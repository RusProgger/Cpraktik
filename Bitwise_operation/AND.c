#include <stdio.h>

// Bitwise Operation - Битовые операции

int main() {

    // Побитовое AND & (И)

    int a = 1;
    int b = 2;

    // printf("A = %d\nB = %d\n", a, b);

    int res = a & b;

    printf("%d\n", res);

    // То есть результат 1 получается только если оба бита равны 1.

    

    return 0;
}