#include <stdio.h>

int main() {

    // ^ Это XOR, или «исключающее ИЛИ».

    // Если значения отличаются → результат 1. Если одинаковые → 0.

    printf("5 ^ 3 = %d\n", 5 ^ 3);
    printf("1 ^ 2 = %d\n", 1 ^ 2);
    printf("1 ^ 3 = %d\n", 1 ^ 3);
    printf("4 ^ 5 = %d\n", 4 ^ 5);


    return 0;
}