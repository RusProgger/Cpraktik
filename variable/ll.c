#include <stdio.h>

int main() {

    // long long int 

    long long int bigNumber = 66435676576463437LL;

    // long int

    long int numB = 642910056L;

    char repo1 = 65;

    printf("Long long int value: %lld\n", bigNumber);
    printf("Long int value: %ld\n", numB);
    printf("Char value: %ld\n", repo1);

    return 0;
}